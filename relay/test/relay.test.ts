import { SELF, reset } from 'cloudflare:test'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { A, B, C, VECTOR_PAIR, VECTOR_SIG, VECTOR_TS, envelope, joinRoom, nextMessage, pair, pairOf, record, signed, wsQuery } from './helpers'

const T0 = Date.UTC(2025, 10, 15, 16, 0, 0)
const settle = () => new Promise((r) => setTimeout(r, 50))
beforeEach(() => { vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(T0) })
afterEach(async () => { vi.useRealTimers(); await reset() })

describe('signatures', () => {
  it('accepts a signed create and records the device', async () => {
    const a = await A()
    const r = await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))
    expect(r.status).toBe(201)
  })
  it('rejects a bad signature, a stale clock, a missing header and an id that does not match the key', async () => {
    const a = await A(), b = await B()
    const h = await a.sign('POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))
    const post = (headers: Record<string, string>, body = record(a, 'Ana')) => SELF.fetch('https://relay/pair/PT-KSV-7Q4K', { method: 'POST', body, headers })
    expect((await post({ ...h, 'X-Elsewhere-Sig': h['X-Elsewhere-Sig'].replace(/^./, (c) => (c === 'A' ? 'B' : 'A')) })).status).toBe(401)
    expect((await post(h, record(a, 'Eve'))).status).toBe(401)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'), { ts: Math.floor(T0 / 1000) - 301 })).status).toBe(401)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'), { ts: Math.floor(T0 / 1000) + 301 })).status).toBe(401)
    expect((await post({})).status).toBe(401)
    expect((await post({ ...h, 'X-Elsewhere-Id': b.id })).status).toBe(401)
  })
  it('verifies the web client interop vector over GET /room/{pairId}', async () => {
    vi.setSystemTime(VECTOR_TS * 1000)
    const a = await A(), b = await B()
    const pid = await pair(a, b)
    expect(pid).toBe(VECTOR_PAIR)
    const r = await SELF.fetch(`https://relay/room/${pid}?id=${a.id}&ts=${VECTOR_TS}&sig=${encodeURIComponent(VECTOR_SIG)}`, { headers: { Upgrade: 'websocket' } })
    expect(r.status).toBe(101)
    r.webSocket!.accept(); r.webSocket!.close()
  })
  it('an unknown device cannot sign anything but pairing', async () => {
    const a = await A()
    expect((await signed(a, 'GET', '/room/YNSO47A5246FH5MO/last')).status).toBe(401)
  })
})

describe('pair codes', () => {
  it('create → claim → poll hands each side the other record, then the code is gone', async () => {
    const a = await A(), b = await B()
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))).status).toBe(201)
    const pending = await signed(a, 'GET', '/pair/PT-KSV-7Q4K')
    expect(pending.status).toBe(204)
    const claim = await signed(b, 'POST', '/pair/PT-KSV-7Q4K/claim', record(b, 'Bo'))
    expect(claim.status).toBe(200)
    expect(await claim.json()).toEqual({ signPub: a.signPub, kxPub: a.kxPub, kxSig: a.kxSig, name: 'Ana', deviceId: a.id })
    const poll = await signed(a, 'GET', '/pair/PT-KSV-7Q4K')
    expect(poll.status).toBe(200)
    expect(await poll.json()).toEqual({ signPub: b.signPub, kxPub: b.kxPub, kxSig: b.kxSig, name: 'Bo', deviceId: b.id })
    expect((await signed(a, 'GET', '/pair/PT-KSV-7Q4K')).status).toBe(404)
  })
  it('rejects malformed codes; a live code is 409 to its owner and a blank 403 to anyone else', async () => {
    const a = await A(), b = await B()
    expect((await signed(a, 'POST', '/pair/PT-LIS-7Q4K', record(a, 'Ana'))).status).toBe(400)
    expect((await signed(a, 'POST', '/pair/hello', record(a, 'Ana'))).status).toBe(400)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))).status).toBe(201)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))).status).toBe(409)
    const probe = await signed(b, 'POST', '/pair/PT-KSV-7Q4K', record(b, 'Bo'))
    expect(probe.status).toBe(403)
    expect(await probe.text()).toBe('forbidden')
  })
  it('a record whose kxSig does not verify under its signPub is refused, before any code is touched', async () => {
    const a = await A(), b = await B()
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana', { kxPub: b.kxPub }))).status).toBe(400)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana', { kxSig: b.kxSig }))).status).toBe(400)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', JSON.stringify({ signPub: a.signPub, kxPub: a.kxPub, name: 'Ana' }))).status).toBe(400)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))).status).toBe(201)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4K/claim', record(b, 'Bo', { kxSig: a.kxSig }))).status).toBe(400)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4K/claim', record(b, 'Bo'))).status).toBe(200)
  })
  it('probing for codes spends the probe\'s own budget: per device and per IP, counted before the lookup', async () => {
    const a = await A(), b = await B(), c = await C()
    await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))
    for (let i = 0; i < 10; i++) expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4K', record(b, 'Bo'), { ip: '198.51.100.9' })).status).toBe(403)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4K', record(b, 'Bo'), { ip: '198.51.100.9' })).status).toBe(429)
    expect((await signed(b, 'POST', '/pair/PT-NPQ-E001', record(b, 'Bo'), { ip: '198.51.100.9' })).status).toBe(429)
    for (let i = 0; i < 20; i++) expect((await signed(c, 'POST', `/pair/PT-NPQ-E${String(i).padStart(3, '0')}`, record(c, 'Cy'), { ip: '198.51.100.9' })).status).toBe(i < 10 ? 201 : 429)
    expect((await signed(a, 'POST', '/pair/PT-NPQ-E100', record(a, 'Ana'), { ip: '198.51.100.9' })).status).toBe(429)
    expect((await signed(a, 'POST', '/pair/PT-NPQ-E100', record(a, 'Ana'), { ip: '198.51.100.10' })).status).toBe(201)
  })
  it('claim is single use, not for the owner, and poll is owner only', async () => {
    const a = await A(), b = await B(), c = await C()
    await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4K/claim', record(a, 'Ana'))).status).toBe(409)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4K/claim', record(b, 'Bo'))).status).toBe(200)
    expect((await signed(b, 'GET', '/pair/PT-KSV-7Q4K')).status).toBe(403)
    expect((await signed(c, 'POST', '/pair/PT-KSV-7Q4K/claim', record(c, 'Cy'))).status).toBe(410)
    expect((await signed(c, 'POST', '/pair/PT-0000-000/claim', record(c, 'Cy'))).status).toBe(400)
    expect((await signed(c, 'POST', '/pair/PT-ZZZ-ZZZZ/claim', record(c, 'Cy'))).status).toBe(404)
  })
  it('expires after 24 h', async () => {
    const a = await A(), b = await B()
    await signed(a, 'POST', '/pair/PT-KSV-7Q4K', record(a, 'Ana'))
    vi.setSystemTime(T0 + 24 * 3600 * 1000 - 1000)
    expect((await signed(a, 'GET', '/pair/PT-KSV-7Q4K')).status).toBe(204)
    vi.setSystemTime(T0 + 24 * 3600 * 1000 + 1000)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4K/claim', record(b, 'Bo'))).status).toBe(404)
    expect((await signed(a, 'GET', '/pair/PT-KSV-7Q4K')).status).toBe(404)
  })
  it('rate limits: 10 creates an hour per device, 30 claims an hour per IP', async () => {
    const a = await A(), b = await B()
    for (let i = 0; i < 10; i++) expect((await signed(a, 'POST', `/pair/PT-KSV-7Q4${i}`, record(a, 'Ana'))).status).toBe(201)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4Z', record(a, 'Ana'))).status).toBe(429)
    vi.setSystemTime(T0 + 3600 * 1000 + 1)
    expect((await signed(a, 'POST', '/pair/PT-KSV-7Q4Z', record(a, 'Ana'))).status).toBe(201)
    for (let i = 0; i < 30; i++) expect((await signed(b, 'POST', `/pair/PT-NPQ-E${String(i).padStart(3, '0')}/claim`, record(b, 'Bo'), { ip: '198.51.100.7' })).status).toBe(404)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4Z/claim', record(b, 'Bo'), { ip: '198.51.100.7' })).status).toBe(429)
    expect((await signed(b, 'POST', '/pair/PT-KSV-7Q4Z/claim', record(b, 'Bo'), { ip: '198.51.100.8' })).status).toBe(200)
  })
})

describe('rooms', () => {
  it('only the two members may join; a stale or forged query is refused', async () => {
    const a = await A(), b = await B(), c = await C()
    const pid = await pair(a, b)
    await signed(c, 'POST', '/pair/PT-CCC-CCCC', record(c, 'Cy'))
    expect((await joinRoom(c, pid)).status).toBe(403)
    expect((await SELF.fetch(`https://relay/room/${pid}${await wsQuery(a, pid, Math.floor(T0 / 1000) - 400)}`, { headers: { Upgrade: 'websocket' } })).status).toBe(401)
    expect((await SELF.fetch(`https://relay/room/${pid}${await wsQuery(a, await pairOf(a, c))}`, { headers: { Upgrade: 'websocket' } })).status).toBe(401)
    expect((await SELF.fetch(`https://relay/room/${pid}${await wsQuery(a, pid)}`)).status).toBe(426)
    const ok = await joinRoom(a, pid)
    expect(ok.status).toBe(101)
    ok.webSocket!.accept(); ok.webSocket!.close()
  })
  it('fans each message to the other peer, never back to the sender', async () => {
    const a = await A(), b = await B()
    const pid = await pair(a, b)
    const wa = (await joinRoom(a, pid)).webSocket!, wb = (await joinRoom(b, pid)).webSocket!
    wa.accept(); wb.accept()
    const got: string[] = []
    wa.addEventListener('message', (e) => got.push(`a:${e.data}`))
    const onB = nextMessage(wb)
    wa.send(envelope(a.id))
    expect(await onB).toBe(envelope(a.id))
    const onA = nextMessage(wa)
    wb.send(envelope(b.id))
    expect(await onA).toBe(envelope(b.id))
    expect(got).toEqual([`a:${envelope(b.id)}`])
    wa.close(); wb.close()
  })
  it('drops oversize messages, a sender faster than one per 10 s, and envelopes claiming another sender', async () => {
    const a = await A(), b = await B()
    const pid = await pair(a, b)
    const wa = (await joinRoom(a, pid)).webSocket!, wb = (await joinRoom(b, pid)).webSocket!
    wa.accept(); wb.accept()
    const got: string[] = []
    wb.addEventListener('message', (e) => got.push(String(e.data)))
    wa.send(envelope(a.id, 600))
    wa.send(envelope(b.id))
    wa.send(envelope(a.id))
    wa.send(envelope(a.id, 1))
    await nextMessage(wb)
    await settle()
    vi.setSystemTime(T0 + 11_000)
    wa.send(envelope(a.id, 2))
    await nextMessage(wb)
    expect(got).toEqual([envelope(a.id), envelope(a.id, 2)])
    wa.close(); wb.close()
  })
  it('keeps the last message per sender for 15 min: late joiner reads it over /last', async () => {
    const a = await A(), b = await B(), c = await C()
    const pid = await pair(a, b)
    const wa = (await joinRoom(a, pid)).webSocket!
    wa.accept()
    wa.send(envelope(a.id))
    await vi.waitFor(async () => { const r = await signed(a, 'GET', `/room/${pid}/last`); expect(r.status).toBe(200); expect(await r.json()).toEqual([JSON.parse(envelope(a.id))]) })
    const asB = await signed(b, 'GET', `/room/${pid}/last`)
    expect(await asB.json()).toEqual([JSON.parse(envelope(a.id))])
    await signed(c, 'POST', '/pair/PT-CCC-CCCC', record(c, 'Cy'))
    expect((await signed(c, 'GET', `/room/${pid}/last`)).status).toBe(403)
    vi.setSystemTime(T0 + 15 * 60_000 + 1000)
    expect(await (await signed(b, 'GET', `/room/${pid}/last`)).json()).toEqual([])
    wa.close()
  })
})

describe('tombstone', () => {
  it('DELETE /devices/me wipes codes, pair memberships and last pings for that device', async () => {
    const a = await A(), b = await B()
    const pid = await pair(a, b)
    await signed(a, 'POST', '/pair/PT-AAA-AAAA', record(a, 'Ana'))
    const wa = (await joinRoom(a, pid)).webSocket!
    wa.accept(); wa.send(envelope(a.id))
    await vi.waitFor(async () => expect(await (await signed(b, 'GET', `/room/${pid}/last`)).json()).toHaveLength(1))
    wa.close()
    expect((await signed(a, 'DELETE', '/devices/me')).status).toBe(204)
    expect((await signed(a, 'GET', '/pair/PT-AAA-AAAA')).status).toBe(401)
    expect((await signed(b, 'POST', '/pair/PT-AAA-AAAA/claim', record(b, 'Bo'))).status).toBe(404)
    expect((await joinRoom(b, pid)).status).toBe(403)
    expect((await signed(b, 'GET', `/room/${pid}/last`)).status).toBe(403)
  })
})
