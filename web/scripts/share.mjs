import puppeteer from 'puppeteer-core'
import fs from 'node:fs'
const dir = '/tmp/elsewhere-share'; fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir)
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader', '--window-size=1400,900'] })
const page = await browser.newPage()
await page.setViewport({ width: 1440, height: 900 })
page.on('console', m => { const t = m.text(); if (!/vite|DevTools|Failed to load/.test(t)) console.log('CONSOLE', m.type(), t.slice(0, 600)) })
page.on('pageerror', e => console.log('PAGEERROR', e.message))
const cdp = await page.createCDPSession()
await cdp.send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: dir })
await page.goto(process.argv[2] ?? 'http://localhost:5173/#trips', { waitUntil: 'networkidle0', timeout: 60000 })
await page.evaluate(() => window.addEventListener('unhandledrejection', e => console.log('UNHANDLED', e.reason?.message ?? String(e.reason))))
await page.hover(`${process.env.SEL ?? '.pass:nth-of-type(2)'}`)
await page.screenshot({ path: '../.impeccable/review/share-hover.png' })
const t0 = Date.now()
await page.click(`${process.env.SEL ?? '.pass:nth-of-type(2)'} .save`)
while (Date.now() - t0 < 20000 && !fs.readdirSync(dir).some(f => f.endsWith('.png'))) await new Promise(r => setTimeout(r, 200))
console.log('files', fs.readdirSync(dir), `${Date.now() - t0}ms`)
await browser.close()
