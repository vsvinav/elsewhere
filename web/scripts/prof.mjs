import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--window-size=1440,900'] })
const page = await browser.newPage(); await page.setViewport({ width: 1440, height: 900 })
await page.goto('http://localhost:5173/#' + (process.argv[2] ?? 'play'), { waitUntil: 'networkidle0', timeout: 60000 })
await new Promise(r => setTimeout(r, 5000))
const cdp = await page.createCDPSession()
await cdp.send('Profiler.enable'); await cdp.send('Profiler.setSamplingInterval', { interval: 500 }); await cdp.send('Profiler.start')
await new Promise(r => setTimeout(r, 5000))
const { profile } = await cdp.send('Profiler.stop')
const self = new Map(), byId = new Map(profile.nodes.map(n => [n.id, n]))
const dt = profile.timeDeltas; const total = dt.reduce((a, b) => a + b, 0)
profile.samples.forEach((id, i) => { const n = byId.get(id); const k = `${n.callFrame.functionName || '(anon)'} ${n.callFrame.url.split('/').slice(-2).join('/').split('?')[0]}:${n.callFrame.lineNumber}`; self.set(k, (self.get(k) ?? 0) + dt[i]) })
console.log('total ms', Math.round(total / 1000))
;[...self.entries()].sort((a, b) => b[1] - a[1]).slice(0, 30).forEach(([k, v]) => console.log(String(Math.round(v / 1000)).padStart(6), k.slice(0, 110)))
await browser.close()
