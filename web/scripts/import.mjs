import puppeteer from 'puppeteer-core'
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal','--enable-gpu','--window-size=1440,900'] })
const page = await browser.newPage(); await page.setViewport({ width: 1440, height: 900 })
page.on('pageerror', e => console.log('PAGEERROR', e.message)); page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 200)) })
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle0', timeout: 60000 })
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
await new Promise(r => setTimeout(r, 1000))
await page.screenshot({ path: '../.impeccable/review/home-record.png' })
const input = await page.$('input[type=file]')
const t0 = Date.now()
await input.uploadFile(process.argv[2] ?? '../timeline.json')
await page.waitForFunction(() => document.body.innerText.includes('Your export') || document.body.innerText.includes("Couldn't read"), { timeout: 120000 })
console.log('imported in', Date.now() - t0, 'ms')
await new Promise(r => setTimeout(r, 1500))
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
await page.screenshot({ path: '../.impeccable/review/home-imported.png' })
console.log(await page.evaluate(() => [...document.querySelectorAll('.field')].map(f => f.innerText.replace(/\n/g, ': ')).filter(t => /Source|File|Segments|Named|Record:/.test(t)).join(' | ')))
// reload: must come back from IndexedDB
await page.reload({ waitUntil: 'networkidle0' })
console.log('after reload:', await page.evaluate(() => document.body.innerText.includes('Your export') ? 'mine' : 'sample'))
await browser.close()
